import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { writeSnapshot, catalogHashes } from "./catalog-snapshot.mjs";
const root = fileURLToPath(new URL("..", import.meta.url));
if (process.argv.includes("--check")) {
  const snapshot = JSON.parse(fs.readFileSync(path.join(root, "i18n/generated/snapshot.json"), "utf8"));
  const actual = catalogHashes(root);
  const changed = [...new Set([...Object.keys(snapshot), ...Object.keys(actual)])].filter(name => snapshot[name] !== actual[name]);
  if (changed.length) throw new Error(`Catalog output differs; regenerate with the pinned compiler: ${changed.join(", ")}`);
} else {
  if (!process.env.I18N_COMPILER) throw new Error("Set I18N_COMPILER to the pinned compiler; see i18n/README.md");
  for (const [target, destination] of [["esm", "i18n/generated"], ["rust", "crates/observer-model/i18n/generated"]]) {
    execFileSync(process.env.I18N_COMPILER, ["targets", path.join(root, "i18n/catalog"), "--channel", "production", "--target", target, "--out", path.join(root, destination)], {stdio: "inherit"});
  }
  const meta = fs.readdirSync(path.join(root,"i18n/catalog/meta")).filter(name=>name.endsWith(".json")).sort();
  const args = Object.fromEntries(meta.map(name=>{
    const sidecar = JSON.parse(fs.readFileSync(path.join(root,"i18n/catalog/meta",name),"utf8"));
    return [name.slice(0,-5),sidecar.arguments.map(arg=>[arg.name,arg.type])];
  }));
  fs.writeFileSync(path.join(root,"i18n/arguments.ts"), `// Generated by scripts/i18n.mjs.\nexport const argumentsById: Record<string, readonly (readonly [string, string])[]> = ${JSON.stringify(args,null,2)};\n`);
  const locales = fs.readdirSync(path.join(root,"crates/observer-model/i18n/generated/rust/windows")).filter(name=>name.endsWith(".ftl")).map(name=>name.slice(0,-4)).sort();
  fs.writeFileSync(path.join(root,"crates/observer-model/i18n/locales.rs"), `// Generated by scripts/i18n.mjs.\npub const SUPPORTED_LOCALES: &[&str] = &[${locales.map(tag=>JSON.stringify(tag)).join(", ")}];\n`);
  writeSnapshot(root);
}
